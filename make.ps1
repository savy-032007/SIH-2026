<#
.SYNOPSIS
  Windows shim for the Makefile. Same target names, no GNU make required.

.EXAMPLE
  ./make.ps1 up
  ./make.ps1 seed
  ./make.ps1 test
  ./make.ps1 revision -m "add certificate table"
#>
[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$Target = 'help',

    [Parameter(ValueFromRemainingArguments = $true)]
    [string[]]$Rest
)

$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot

function Invoke-Checked {
    param([string]$Exe, [string[]]$Arguments)
    & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}

function Compose { param([string[]]$Arguments) Invoke-Checked 'docker' (@('compose') + $Arguments) }
function Api { param([string[]]$Arguments) Compose (@('exec', '-T', 'api') + $Arguments) }

function Assert-Docker {
    docker info --format '{{.ServerVersion}}' 2>$null | Out-Null
    if ($LASTEXITCODE -ne 0) {
        Write-Host 'Docker daemon is not reachable. Start Docker Desktop and try again.' -ForegroundColor Red
        exit 1
    }
}

function Ensure-Env {
    if (-not (Test-Path '.env')) {
        Copy-Item '.env.example' '.env'
        Write-Host 'created .env from .env.example' -ForegroundColor Yellow
    }
}

function Get-EnvValue {
    param([string]$Name, [string]$Default)
    if (-not (Test-Path '.env')) { return $Default }
    $line = Select-String -Path '.env' -Pattern "^$Name=" -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($null -eq $line) { return $Default }
    return ($line.Line -replace "^$Name=", '').Trim()
}

switch ($Target.ToLowerInvariant()) {

    'help' {
        Write-Host ''
        Write-Host '  APAAR platform tasks (./make.ps1 <target>)' -ForegroundColor Cyan
        Write-Host ''
        @(
            @('up',        'Build and start all services'),
            @('down',      'Stop all services (keeps the database volume)'),
            @('restart',   'Restart the api service'),
            @('logs',      'Tail logs for all services'),
            @('ps',        'Show service status'),
            @('seed',      'Migrate, generate synthetic data, load it, print demo credentials'),
            @('generate',  'Regenerate the synthetic dataset only'),
            @('migrate',   'Apply database migrations'),
            @('revision',  'Autogenerate a migration: ./make.ps1 revision -m "msg"'),
            @('test',      'Run all tests'),
            @('test-api',  'Run backend tests'),
            @('test-web',  'Typecheck the web app'),
            @('fmt',       'Format Python sources'),
            @('lint',      'Lint Python sources'),
            @('shell',     'Open a shell in the api container'),
            @('psql',      'Open a psql prompt'),
            @('clean',     'Stop services and DELETE the database volume and generated data'),
            @('demo-reset','Full demo reset (Phase 5)')
        ) | ForEach-Object { Write-Host ('  {0,-12} {1}' -f $_[0], $_[1]) }
        Write-Host ''
    }

    'env' { Ensure-Env }

    'up' {
        Assert-Docker
        Ensure-Env
        Compose @('up', '-d', '--build')
        Write-Host ''
        Write-Host ("api    -> http://localhost:{0}/docs" -f (Get-EnvValue 'API_PORT' '8000'))
        Write-Host ("mock   -> http://localhost:{0}/docs" -f (Get-EnvValue 'MOCK_ABC_PORT' '9001'))
        Write-Host ("web    -> http://localhost:{0}" -f (Get-EnvValue 'WEB_PORT' '3000'))
        Write-Host ''
        Write-Host 'next:  ./make.ps1 seed' -ForegroundColor Green
    }

    'down'    { Compose @('down') }
    'restart' { Compose @('restart', 'api') }
    'logs'    { Compose @('logs', '-f', '--tail=100') }
    'ps'      { Compose @('ps') }

    'generate' { Assert-Docker; Api @('python', '-m', 'generator.generate') }
    'seed'     { Assert-Docker; Api @('python', '-m', 'app.seed.run', '--reset') }
    'migrate'  { Assert-Docker; Api @('alembic', 'upgrade', 'head') }

    'revision' {
        Assert-Docker
        $message = 'autogenerated'
        for ($i = 0; $i -lt $Rest.Count; $i++) {
            if ($Rest[$i] -in @('-m', '--message') -and ($i + 1) -lt $Rest.Count) { $message = $Rest[$i + 1] }
        }
        Api @('alembic', 'revision', '--autogenerate', '-m', $message)
    }

    'test' {
        Assert-Docker
        Api @('pytest', '-q')
        Compose @('exec', '-T', 'web', 'npx', 'tsc', '--noEmit')
    }
    'test-api' { Assert-Docker; Api @('pytest', '-q') }
    'test-web' { Assert-Docker; Compose @('exec', '-T', 'web', 'npx', 'tsc', '--noEmit') }

    'fmt'  { Api @('ruff', 'format', 'app', 'tests') }
    'lint' { Api @('ruff', 'check', 'app', 'tests') }

    'shell' { Compose @('exec', 'api', 'bash') }
    'psql'  { Compose @('exec', 'postgres', 'psql', '-U', (Get-EnvValue 'POSTGRES_USER' 'apaar'), '-d', (Get-EnvValue 'POSTGRES_DB' 'apaar')) }

    'clean' {
        Compose @('down', '-v')
        if (Test-Path 'data/seed') { Remove-Item -Recurse -Force 'data/seed' }
    }

    'demo-reset' {
        Write-Host 'demo-reset lands in Phase 5 (SPEC 12). For now: ./make.ps1 clean; ./make.ps1 up; ./make.ps1 seed' -ForegroundColor Yellow
    }

    default {
        Write-Host "unknown target '$Target'. Run ./make.ps1 help" -ForegroundColor Red
        exit 1
    }
}
